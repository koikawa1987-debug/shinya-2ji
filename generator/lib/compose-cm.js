const 使う行 = (n) => (n === 4 ? [0, 1, 4, 5] : [0, 1, 2, 3, 4, 5]);

const 字数 = (s) => [...String(s).replace(/[\s、。「」『』・…—-]/g, '')].length;

/* ---------- 略号 ---------- */

function 新しい略号(rnd, 既存, 社名) {
  const 頭 = /^[A-Za-z]/.test(社名) ? 社名[0].toUpperCase() : 'ABCDEFGHJKLMNPRSTWY'[Math.floor(rnd() * 19)];
  for (let d = 1; d <= 9; d++) {
    const 案 = `${頭}${d}`;
    if (!既存.includes(案)) return 案;
  }
  for (const a of 'ABCDEFGHJKLMNPRSTWY') {
    for (let d = 1; d <= 9; d++) {
      const 案 = `${a}${d}`;
      if (!既存.includes(案)) return 案;
    }
  }
  return null;
}

/* ---------- 組み立て ---------- */

/** その媒体に出しうるスポンサーのうち、素材の少ない社を優先する */
function 出稿社を選ぶ(station, 媒体, rnd) {
  const 候補 = station.スポンサー.filter((s) => {
    const 波 = s.出稿方針?.媒体;
    return !波 || 波.length === 0 || 波.includes(媒体);
  });
  if (!候補.length) return null;
  const 本数 = (s) => station.CM素材.filter((c) => c.スポンサーid === s.id && (c.媒体 ?? TV) === 媒体).length;
  const 最少 = Math.min(...候補.map(本数));
  const 薄い = 候補.filter((s) => 本数(s) === 最少);
  return pick(rnd, 薄い);
}

/**
 * 新しいCM素材を1本組み立てる。作れなければ null を返す。
 */
export function composeCM(station, 日付, 媒体 = TV) {
  const rnd = seeded(`${日付}/${媒体}/CM`);
  const sponsor = 出稿社を選ぶ(station, 媒体, rnd);
  if (!sponsor) return null;

  const 物候補 = 品目[sponsor.業種] ?? 既定品目;
  // 重複は「愛称を除いた商品の正体」で見る。
  // 同じ品を愛称だけ変えて出し直すのは、素材が増えたことにならない。
  const 既存正体 = new Set(station.CM素材.map((c) => String(c.商品名).replace(/〈.*〉/, '')));

  const 略号 = 新しい略号(rnd, station.CM素材.map((c) => c.略号), sponsor.社名);
  if (!略号) return null;

  // 概念×品目×愛称×尺 を順に試す。名前の重複と字数超過は、どちらも次の案へ送る。
  // 長い概念は短い尺に収まらないことがあるので、ここで捨てずに組み替える。
  // 種で並べ替えてから探す。先頭固定だと愛称も概念も同じものばかり出る。
  const shuffle = (a) => a.map((v) => [rnd(), v]).sort((x, y) => x[0] - y[0]).map(([, v]) => v);
  const 概念順 = shuffle([...概念.keys()]);
  const 尺順 = shuffle([...CM_LENGTHS[媒体]]);
  const 物順 = shuffle([...物候補]);
  const 愛称順 = shuffle([...愛称]);
  const ラジオ = 媒体 === RADIO;

  for (const ci of 概念順) {
    const c = 概念[ci];
    for (const 物 of 物順) {
      const 正体 = c.接頭(物);
      if (既存正体.has(正体)) continue;
      const 読み = c.行(物);
      const 絵 = c.絵(物);
      const 音 = c.音(物);
      const 締め = `${正体}。${sponsor.社名}。`;

      for (const 尺 of 尺順) {
        const 秒配分 = 行割り[尺];
        const idx = 使う行(秒配分.length);
        const ナレーション全文 = idx.map((k) => 読み[k]).join('') + 締め;
        if (字数(ナレーション全文) > ナレーション上限(尺, 媒体)) continue;

        const 構成案 = idx.map((k, i) => {
          const 台詞 = `N ${読み[k]}`;
          return ラジオ
            ? { 時間: 秒配分[i], 音: 音[k], 原稿: 台詞 }
            : { 時間: 秒配分[i], 映像: 絵[k], 音声: `${音[k]}／${台詞}` };
        });

        return {
          媒体,
          スポンサーid: sponsor.id,
          商品名: `${正体}〈${愛称順[0]}〉`,
          尺,
          略号,
          使用期間: { 開始: 日付, 終了: addDays(日付, 90) },
          構成案,
          ナレーション全文,
          没案: c.没(物),
        };
      }
    }
  }
  return null;
}
