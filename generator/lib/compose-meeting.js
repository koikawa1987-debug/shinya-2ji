// 打ち切りと新番組は実際の数字から決め、議事録はその決定過程を文章にする。
// 数字が先にあるので、擁護する側と切りたがる側の言い分は自動的に噛み合う。

import { TV, RADIO } from './config.js';
import { addDays, daysBetween, toMinutes, toHHMM } from './time.js';
import { DAY_START_MIN, DAY_END_MIN } from './config.js';
import { 漢数字 } from './compose.js';

function seeded(seed) {
  let h = 2166136261;
  for (const ch of String(seed)) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h ^= h << 13; h >>>= 0;
    h ^= h >>> 17;
    h ^= h << 5; h >>>= 0;
    return h / 4294967296;
  };
}
const pick = (rnd, a) => a[Math.floor(rnd() * a.length) % a.length];
const shuffleWith = (rnd, a) => a.map((v) => [rnd(), v]).sort((x, y) => x[0] - y[0]).map(([, v]) => v);

/** 小数を漢数字の読みにする（四・〇、〇・一二） */
function 数読み(n, 桁) {
  const s = Number(n).toFixed(桁);
  return [...s].map((ch) => (ch === '.' ? '・' : 漢数字(Number(ch)))).join('');
}

