/* ---------- 組み立て ---------- */

const 時間帯名 = (開始時刻) => {
  const h = Number(String(開始時刻).split(':')[0]);
  if (h < 9) return '朝';
  if (h < 12) return '午前';
  if (h < 16) return '昼';
  if (h < 19) return '夕方';
  if (h < 23) return '夜';
  return '深夜';
};

const 尺表記 = (分) => {
  if (分 >= 60 && 分 % 60 === 0) return `${漢数字(分 / 60)}時間`;
  if (分 > 60) return `${漢数字(Math.floor(分 / 60))}時間${漢数字(分 % 60)}分`;
  return `${漢数字(分)}分`;
};

/**
 * その日の各番組の回を組み立てる。
 * rows は buildSkeleton が返した番組行（テレビ・ラジオ両方）。
 */
export function composeEpisodes(station, 日付, 曜日, 行たち) {
  const progById = new Map(station.番組.map((p) => [p.id, p]));
  const 回 = [];

  for (const row of 行たち) {
    const p = progById.get(row.番組id);
    if (!p) continue;
    const rnd = seeded(`${日付}/${p.id}/回`);
    const 帯 = 時間帯名(row.開始時刻);
    const c = {
      rnd,
      曜: 曜日,
      季節: 季節(日付),
      時間帯: 帯,
      夜: 帯 === '夜' || 帯 === '深夜',
      ラジオ: (p.媒体 ?? TV) === RADIO,
      // その日その番組で扱う品はひとつに固定する
      品: pick(rnd, 品目),
      尺表記: 尺表記(row.尺),
      // その番組が何回目の放送か。履歴の件数から数える
      回: (p.視聴率履歴?.length ?? 0) + 1,
      通算日: daysBetween(station.開局日, 日付) + 1,
      媒体: p.媒体 ?? TV,
    };

    const 上書き = 固有[p.id]?.(c);
    if (上書き) {
      回.push({ 番組id: p.id, ...上書き, ゲスト: [] });
      continue;
    }

    const t = 型[p.ジャンル] ?? 既定型;
    const 断片 = picks(rnd, t.断片, Math.min(2, t.断片.length)).map((f) => f(c));
    const 締め = pick(rnd, t.締め)(c);
    回.push({
      番組id: p.id,
      サブタイトル: t.見出し(c),
      今回の内容: `${断片.join('▽')}▽${締め}。`,
      ゲスト: [],
    });
  }

  return 回;
}

/** その日の編成メモ */
export function composeMemo(station, 日付, 曜日, tv行, radio行) {
  const rnd = seeded(`${日付}/メモ`);
  const 通算 = daysBetween(station.開局日, 日付) + 1;
  const 素 = [];

  if (通算 % 30 === 0) 素.push(`開局から${漢数字(通算 / 30)}か月。`);
  if (!radio行.length) 素.push('ラジオは終日停波。');

  素.push(
    pick(rnd, [
      '第二スタジオの空調は今週も工事中。深夜帯の機材は移したまま運用する。',
      '送出要員が一名足りず、早朝は自動送出で通す。',
      '新聞社の締切に間に合わせるため、番組表は前日十七時に送っている。',
      '副調整室の照明を一列落として運用中。営業からの申し入れによる。',
      '回線使用料の見直しについて、次回の定例で報告がある。',
      'テープの在庫が少なく、今週は上書きで回している。',
    ]),
  );

  if (曜日 === '日') 素.push('日曜二十三時台のテレビは編成なし。単発枠が月曜から土曜のみのため。');

  return 素.join('');
}
