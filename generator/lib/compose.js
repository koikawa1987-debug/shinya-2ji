/* ---------- 決定論の乱数 ---------- */

function seeded(seed) {
  let h = 2166136261;
  for (const ch of String(seed)) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h ^= h << 13; h >>>= 0;
    h ^= h >>> 17;
    h ^= h << 5; h >>>= 0;
    return h / 4294967296;
  };
}

/** 種から引く。同じ種・同じ配列なら必ず同じ要素 */
const pick = (rnd, arr) => arr[Math.floor(rnd() * arr.length) % arr.length];

/** 重複なしで n 個引く */
function picks(rnd, arr, n) {
  const pool = [...arr];
  const out = [];
  for (let i = 0; i < n && pool.length; i++) out.push(...pool.splice(Math.floor(rnd() * pool.length), 1));
  return out;
}

/* ---------- 漢数字 ---------- */

const 数字 = ['〇','一','二','三','四','五','六','七','八','九'];
export function 漢数字(n) {
  if (n < 0) return String(n);
  if (n === 0) return '〇';
  if (n < 10) return 数字[n];
  if (n < 20) return '十' + (n % 10 ? 数字[n % 10] : '');
  if (n < 100) return 数字[Math.floor(n / 10)] + '十' + (n % 10 ? 数字[n % 10] : '');
  if (n < 1000) {
    const h = Math.floor(n / 100), r = n % 100;
    return (h > 1 ? 数字[h] : '') + '百' + (r ? 漢数字(r) : '');
  }
  return String(n);
}

