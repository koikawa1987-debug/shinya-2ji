const station = readJSON(STATION_FILE);
const staff = readJSON(path.join(LIB, 'seed-staff.json'));
const byId = new Map(station.人物.map((h) => [h.id, h]));

let 足した項目 = 0;
for (const [id, patch] of Object.entries(追加)) {
  const h = byId.get(id);
  if (!h) {
    console.warn(`人物 ${id} が見つかりません`);
    continue;
  }
  Object.assign(h, patch);
  足した項目 += 1;
}

for (const s of staff) {
  if (byId.has(s.id)) continue;
  station.人物.push(s);
}

// 関係は双方向に見えるようにしておく。片側にしか書いていなくても相手から辿れる
const idを持つ = new Set(station.人物.map((h) => h.id));
for (const h of station.人物) {
  h.関係 = (h.関係 ?? []).filter((r) => idを持つ.has(r.id) && r.id !== h.id);
}

writeJSON(STATION_FILE, station);

const 部署別 = {};
for (const h of station.人物) 部署別[h.部署 ?? '未設定'] = (部署別[h.部署 ?? '未設定'] ?? 0) + 1;
console.log(`✓ 人物 ${station.人物.length}名（既存 ${足した項目}名に肉付け、${staff.length}名を追加）`);
console.log('  ' + Object.entries(部署別).map(([k, v]) => `${k} ${v}`).join(' ／ '));

if (writeSeed) {
  const SEED = path.join(LIB, 'seed-station.json');
  const seed = readJSON(SEED);
  seed.人物 = JSON.parse(JSON.stringify(station.人物));
  writeJSON(SEED, seed);
  console.log('✓ seed-station.json を更新しました');
}

syncDocsData();
